"""Concord Biotech bear/base/bull valuation to FY29.

Run: python -I -X utf8 model/valuation.py
Writes model/valuation.md and model/valuation.json next to this file.
All money in Rs crore unless stated. Inputs are tagged with their source in INPUTS.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent

# ---- Inputs (facts) -------------------------------------------------------
INPUTS = {
    "price": (594.0, "Screener overview, 9 Nov 2026, post 1:1 bonus"),
    "shares_cr": (20.9232408, "20,92,32,408 shares after bonus allotment 4 Nov 2026 (BSE)"),
    "fy26_revenue": (1054.9, "AR FY26 p247"),
    "fy26_ebitda": (368.0, "Screener FY26 operating profit"),
    "fy26_pat_owners": (259.2, "AR FY26: EPS Rs 24.78 x 10.46 cr shares"),
    "ttm_pat": (279.0, "Screener TTM net profit (Sep-26)"),
    "ttm_ebitda": (403.0, "Screener TTM operating profit"),
    "fy26_depreciation": (74.0, "Screener FY26"),
    "net_fixed_assets_sep26": (771.0, "Screener Sep-26 fixed assets"),
    "cash_and_liquid_sep26": (445.8, "deck-q2fy27 p11: cash 7.7 + current investments 438.1"),
    "palvella_mar26": (84.1, "AR FY26 p238, listed, held through OCI"),
    "debt_sep26": (2.0, "Screener Sep-26 borrowings"),
    "fy26_fcf": (172.0, "Screener FY26 free cash flow"),
}
V = {k: v[0] for k, v in INPUTS.items()}

COST_OF_EQUITY = 0.12      # assumption: India large/mid-cap pharma, stated in report
VALUATION_DATE_TO_MAR28_YEARS = 1.39  # 9 Nov 2026 to 31 Mar 2028
TAX = 0.245                # [G] 24-25% (Q2 FY27 call p10)
INTEREST = 1.0             # debt-free; Screener FY26 interest Rs 1 cr

# ---- Scenarios (assumptions) ----------------------------------------------
# growth = revenue growth FY27, FY28, FY29; margin = EBITDA margin FY27..FY29
SCENARIOS = {
    "Bear": {
        "growth": [0.10, 0.11, 0.11],
        "margin": [0.33, 0.34, 0.34],
        "pe": 25.0,
        "why": "FY24-FY26 pattern continues: low-teens growth, price-led share gains keep margin near the H1 FY27 level, injectables slow",
    },
    "Base": {
        "growth": [0.19, 0.19, 0.19],
        "margin": [0.35, 0.365, 0.38],
        "pe": 35.0,
        "why": "Guided path: about 19% growth, margin back to the bottom of the 38-40% guide by FY29 as Unit IV and Stellon fill",
    },
    "Bull": {
        "growth": [0.20, 0.23, 0.23],
        "margin": [0.36, 0.385, 0.40],
        "pe": 42.0,
        "why": "Injectable contracts and Stellon add on top of the API base; margin reaches the top of the guide; market keeps a premium multiple",
    },
}
OTHER_INCOME = [45.0, 50.0, 55.0]      # Screener TTM Rs 46 cr; rises with the cash pile
DEPRECIATION = [78.0, 83.0, 88.0]      # [G] capex Rs 20-30 cr maintenance + Rs 50-60 cr a year in FY27-FY28
CAPEX = [85.0, 85.0, 50.0]


def project(s):
    rows, rev = [], V["fy26_revenue"]
    for i, year in enumerate(["FY27", "FY28", "FY29"]):
        rev = rev * (1 + s["growth"][i])
        ebitda = rev * s["margin"][i]
        pbt = ebitda + OTHER_INCOME[i] - DEPRECIATION[i] - INTEREST
        pat = pbt * (1 - TAX)
        rows.append({"year": year, "revenue": rev, "ebitda": ebitda, "margin": s["margin"][i],
                     "pbt": pbt, "pat": pat, "eps": pat / V["shares_cr"]})
    return rows


def value(s, rows):
    fy29 = rows[-1]
    price_mar28 = fy29["eps"] * s["pe"]
    pv = price_mar28 / (1 + COST_OF_EQUITY) ** VALUATION_DATE_TO_MAR28_YEARS
    palvella_ps = V["palvella_mar26"] / V["shares_cr"]
    total = pv + palvella_ps
    return {"fy29_eps": fy29["eps"], "pe": s["pe"], "price_mar28": price_mar28,
            "pv_today": pv, "palvella_ps": palvella_ps, "value_ps": total,
            "vs_price": total / V["price"] - 1}


def readout(base_gap, mgmt_verdict="AMBER"):
    label = "ATTRACTIVE" if base_gap >= 0.20 else ("STRETCHED" if base_gap <= -0.20 else "FAIR")
    if mgmt_verdict == "RED" and label == "ATTRACTIVE":
        label = "FAIR"
    return label


def main():
    out = {"inputs": INPUTS, "cost_of_equity": COST_OF_EQUITY, "tax": TAX, "scenarios": {}}
    md = ["# Concord Biotech - valuation output", "",
          "Generated by model/valuation.py; do not edit by hand.",
          f"Price Rs {V['price']:.0f}, {V['shares_cr']:.4f} cr shares, market cap Rs {V['price']*V['shares_cr']:,.0f} cr.",
          "Method: FY29 EPS x P/E gives a value at 31 Mar 2028 (one year forward), discounted 1.39 years at 12% cost of equity, plus Palvella at book per share.", ""]
    for name, s in SCENARIOS.items():
        rows = project(s)
        v = value(s, rows)
        out["scenarios"][name] = {"assumptions": s, "rows": rows, "value": v}
        md += [f"## {name}", "", s["why"] + ".", "",
               "| Year | Revenue | Growth | EBITDA | Margin | PBT | PAT | EPS (Rs) |", "|---|---|---|---|---|---|---|---|"]
        for i, r in enumerate(rows):
            md.append(f"| {r['year']} | {r['revenue']:,.0f} | {s['growth'][i]*100:.0f}% | {r['ebitda']:,.0f} | {r['margin']*100:.1f}% | {r['pbt']:,.0f} | {r['pat']:,.0f} | {r['eps']:.2f} |")
        md += ["", f"FY29 EPS Rs {v['fy29_eps']:.2f} x {v['pe']:.0f} = Rs {v['price_mar28']:.0f} at Mar-28; today Rs {v['pv_today']:.0f} + Palvella Rs {v['palvella_ps']:.0f} = **Rs {v['value_ps']:.0f}** ({v['vs_price']*100:+.0f}% vs price).", ""]

    base_gap = out["scenarios"]["Base"]["value"]["vs_price"]
    out["readout"] = readout(base_gap)
    md += [f"## Readout", "", f"Base value is {base_gap*100:+.0f}% vs price: **{out['readout']}** (ATTRACTIVE at +20% or more, STRETCHED at -20% or worse; management verdict AMBER, so no cap applies).", ""]

    # Reverse: what FY29 PAT does today's price need at each multiple
    mcap = V["price"] * V["shares_cr"] - V["palvella_mar26"]
    md += ["## What the price implies", "", "Two readings: 'flat' is market cap / P/E (the price simply holds); '12% return' grows today's market cap at the 12% cost of equity to Mar-28 first.", "",
           "| P/E on FY29 | FY29 PAT needed, flat | CAGR from FY26 | FY29 PAT needed, 12% return | CAGR from FY26 |", "|---|---|---|---|---|"]
    implied = []
    for pe in (25, 30, 35, 40):
        flat = mcap / pe
        need = mcap * (1 + COST_OF_EQUITY) ** VALUATION_DATE_TO_MAR28_YEARS / pe
        c0 = (flat / V["fy26_pat_owners"]) ** (1 / 3) - 1
        cagr = (need / V["fy26_pat_owners"]) ** (1 / 3) - 1
        implied.append({"pe": pe, "pat_flat": flat, "cagr_flat": c0, "pat": need, "cagr": cagr})
        md.append(f"| {pe}x | {flat:,.0f} | {c0*100:.1f}% | {need:,.0f} | {cagr*100:.1f}% |")
    out["implied"] = implied

    # Sensitivity: base margins, vary growth and P/E
    md += ["", "## Sensitivity (value per share, Rs; base margins)", "",
           "| Revenue CAGR FY26-29 \\ P/E | 25x | 30x | 35x | 40x | 45x |", "|---|---|---|---|---|---|"]
    sens = []
    for g in (0.10, 0.14, 0.19, 0.23):
        cells = []
        for pe in (25, 30, 35, 40, 45):
            s = dict(SCENARIOS["Base"], growth=[g] * 3, pe=float(pe))
            cells.append(value(s, project(s))["value_ps"])
        sens.append({"growth": g, "values": cells})
        md.append(f"| {g*100:.0f}% | " + " | ".join(f"{c:,.0f}" for c in cells) + " |")
    out["sensitivity"] = sens

    # Cross-checks
    ev = V["price"] * V["shares_cr"] - V["cash_and_liquid_sep26"] - V["palvella_mar26"] + V["debt_sep26"]
    base29 = out["scenarios"]["Base"]["rows"][-1]
    nfa29 = V["net_fixed_assets_sep26"] + sum(CAPEX) - sum(DEPRECIATION)  # approx, from Sep-26
    cross = {
        "ev": ev,
        "ev_ttm_ebitda": ev / V["ttm_ebitda"],
        "ev_fy29_base_ebitda": ev / base29["ebitda"],
        "fcf_yield_fy26": V["fy26_fcf"] / (V["price"] * V["shares_cr"]),
        "pe_ttm": V["price"] * V["shares_cr"] / V["ttm_pat"],
        "fat_fy26": V["fy26_revenue"] / 789.0,
        "fat_fy29_base": base29["revenue"] / nfa29,
    }
    out["cross_checks"] = cross
    md += ["", "## Cross-checks", "",
           f"- Enterprise value (market cap less Rs {V['cash_and_liquid_sep26']:.0f} cr cash and liquid funds, less Palvella, plus debt): Rs {ev:,.0f} cr.",
           f"- EV / TTM EBITDA: {cross['ev_ttm_ebitda']:.1f}x; EV / FY29 base EBITDA: {cross['ev_fy29_base_ebitda']:.1f}x.",
           f"- P/E on TTM PAT Rs {V['ttm_pat']:.0f} cr: {cross['pe_ttm']:.1f}x.",
           f"- FCF yield on FY26 FCF Rs {V['fy26_fcf']:.0f} cr: {cross['fcf_yield_fy26']*100:.1f}%.",
           f"- Fixed asset turnover: FY26 {cross['fat_fy26']:.2f}x; FY29 base {cross['fat_fy29_base']:.2f}x (approximate net block Rs {nfa29:,.0f} cr), back above the FY24 level of 1.77x.",
           ""]

    (HERE / "valuation.md").write_text("\n".join(md), encoding="utf-8")
    (HERE / "valuation.json").write_text(json.dumps(out, indent=1, default=float), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
